"""Generate the offline test-page catalog from the server capability definitions."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# Presentation order/labels only. Capabilities and defaults always come from Python.
DISPLAY_NAMES = {
    "gemini-3.1-flash-image": "Nano Banana 2.1",
    "gemini-3.0-pro-image": "Nano Banana Pro",
    "gemini-3.1-flash-image-lite": "Nano Banana 2 Lite",
    "imagen-4.0-generate-preview": "Imagen 4.0",
    "veo_3_1": "Veo 3.1",
    "omni_1.1_flash": "Omni 1.1 Flash",
}
OUTPUT = ROOT / "static/js/model_catalog.js"


def render_catalog() -> str:
    from src.core.public_models import PUBLIC_MODELS

    order = dict.fromkeys([*DISPLAY_NAMES, *PUBLIC_MODELS])
    catalog = {
        name: {
            **PUBLIC_MODELS[name],
            "displayName": DISPLAY_NAMES.get(name, PUBLIC_MODELS[name]["description"]),
        }
        for name in order
        if name in PUBLIC_MODELS and not PUBLIC_MODELS[name].get("legacy")
    }
    # One model per line keeps generated diffs manageable without an extra JS build tool.
    lines = [
        f"  {json.dumps(name)}: {json.dumps(entry, ensure_ascii=False)}"
        for name, entry in catalog.items()
    ]
    return (
        "// Generated by python scripts/generate_model_fallback.py; do not edit capabilities here.\n"
        "const FALLBACK_MODELS = {\n" + ",\n".join(lines) + "\n};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the committed catalog is stale"
    )
    args = parser.parse_args()
    expected = render_catalog()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(
                "Model fallback is stale. Run: python scripts/generate_model_fallback.py",
                file=sys.stderr,
            )
            return 1
        print("Model fallback matches server capabilities.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
