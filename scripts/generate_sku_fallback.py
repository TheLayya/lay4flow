"""Generate the public API guide's SKU catalog from the server definitions."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OUTPUT = ROOT / "static/js/media_skus.js"
FIELDS = ("id", "type", "public_model", "locked_spec", "allowed_modes", "description")


def render_catalog() -> str:
    from src.core.media_skus import list_sku_models

    lines = [
        "  "
        + json.dumps(
            {field: model[field] for field in FIELDS},
            ensure_ascii=False,
            separators=(",", ":"),
        )
        for model in list_sku_models()
    ]
    return (
        "// Generated by python scripts/generate_sku_fallback.py; do not edit SKU metadata here.\n"
        "const FALLBACK_MEDIA_SKUS = [\n" + ",\n".join(lines) + "\n];\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Fail if the committed catalog is stale"
    )
    args = parser.parse_args()
    expected = render_catalog()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(
                "SKU fallback is stale. Run: python scripts/generate_sku_fallback.py",
                file=sys.stderr,
            )
            return 1
        print("SKU fallback matches server definitions.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
